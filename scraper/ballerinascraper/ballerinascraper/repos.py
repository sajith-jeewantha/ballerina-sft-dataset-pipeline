"""`collect-repos`: Ballerina code from whole repositories, licence-gated and pinned.

For each repository in the configured groups (`repos.groups` in pipeline.yaml):

1. **List** it: an org's public repos, a GitHub search, or an explicit list.
2. **Pre-gate** on the licence GitHub reports: no licence or a copyleft licence is excluded
   without downloading anything.
3. **Pin** the default branch to a commit (`git ls-remote`, no API quota), recorded in
   `config/sources.lock.json` under `repos`, and reused until `--update-lock`.
4. **Snapshot** it with a blobless, shallow, sparse clone: only `*.bal`, `Ballerina.toml`,
   `*.out`, READMEs and the root LICENSE are downloaded.
5. **Gate** on the LICENSE file text (`balpipe_common.licences.decide`). Only `safe` repos keep
   their files; every repo seen gets a row in the licence register.
6. **Store** the files in `repo_files` with their Ballerina project, `distribution`, a Swan Lake
   / legacy classification, a generated-code flag and fingerprints. A `.tar.gz` snapshot goes
   to `data/repos/`.

After the run, `dedup()` marks exact and near-duplicate `.bal` files across all repos. The
earlier group wins (platform, guides, wso2, external, manual), so official copies are kept.
`LIMIT_REPOS` caps how many repos are cloned per run.
"""

