log = logging.getLogger(__name__)

LICENCE_NAMES = re.compile(r"^(LICEN[CS]E|COPYING)(\.(md|txt|rst))?$", re.I)
DISTRIBUTION_RE = re.compile(r'^\s*distribution\s*=\s*"([^"]+)"', re.M)
GENERATED_RE = re.compile(r"auto[- ]?generated|generated by|do not (edit|modify)|this file (was|is) generated", re.I)
# Ballerina 1.x / pre-Swan-Lake constructs
LEGACY_RE = re.compile(
    r"^\s*endpoint\s+[\w:]+\s+\w+|\bbut\s*\{|public\s+function\s+main\s*\(\s*string\s*\.\.\.\s*\w+\s*\)"
    r"|@http:ServiceConfig\s*\{[^}]*\bbasePath\b|^\s*service\s+\w+\s+on\s+new\s+http:Listener|\bpublic\s+type\s+\w+\s+object\s*\{[^}]*\bpublic\s*\{",
    re.M)
SWAN_LAKE_RE = re.compile(
    r"\bservice\s+(/|\"|on\b)|\bresource\s+function\s+(get|post|put|delete|patch|head|options|default)\b"
    r"|\bisolated\s+(function|class|service)\b|\bservice\s+class\b|\bcheck\s+\w+->|->\s*\w+\(|\bconfigurable\s+\w+",
    re.M)
GROUP_PRIORITY_LAST = 99


# --------------------------------------------------------------------------- #
# Listing
# --------------------------------------------------------------------------- #
@dataclass
class RepoInfo:
    full_name: str
    group: str
    priority: int
    intended_use: str
    meta: dict[str, Any]

    @property
    def url(self) -> str:
        return str(self.meta.get("clone_url") or f"https://github.com/{self.full_name}")

    @property
    def default_branch(self) -> str:
        return str(self.meta.get("default_branch") or "HEAD")

    @property
    def has_licence_key(self) -> bool:
        return bool(self.meta.get("license"))

    @property
    def spdx_reported(self) -> str | None:
        return normalize_spdx((self.meta.get("license") or {}).get("spdx_id"))


def _selected(name: str, g: RepoGroupCfg) -> bool:
    if g.include and not any(re.search(p, name) for p in g.include):
        return False
    return not any(re.search(p, name) for p in g.exclude)


def list_group(api: GithubApi, g: RepoGroupCfg) -> Iterator[dict[str, Any]]:
    if g.org:
        for r in sorted(api.org_repos(g.org), key=lambda r: -int(r.get("stargazers_count") or 0)):
            if not r.get("fork") and not r.get("archived") and _selected(r["name"], g):
                yield r
    if g.query:
        page, seen = 1, 0
        while seen < g.max_search_results:
            data = api.json(f"/search/repositories?q={quote_plus(g.query)}&sort=stars&order=desc"
                            f"&per_page=100&page={page}")
            items = data.get("items", []) if isinstance(data, dict) else []
            for r in items:
                seen += 1
                if _selected(r["name"], g):
                    yield r
            if len(items) < 100:
                break
            page += 1
    for full in g.repos:
        r = api.json(f"/repos/{full}")
        if isinstance(r, dict) and r.get("full_name"):
            yield r


def iter_repos(api: GithubApi, cfg: ReposCfg, groups: list[str] | None,
               extra: list[str] | None) -> Iterator[RepoInfo]:
    seen: set[str] = set()
    chosen = [g for g in cfg.groups if groups is None or g.name in groups]
    if extra:
        chosen.append(RepoGroupCfg(name="manual", repos=list(extra), intended_use="manual"))
    for prio, g in enumerate(chosen):
        priority = next((i for i, x in enumerate(cfg.groups) if x.name == g.name), GROUP_PRIORITY_LAST)
        for r in list_group(api, g):
            full = r["full_name"]
            if full.lower() in seen:
                continue
            seen.add(full.lower())
            yield RepoInfo(full, g.name, priority, g.intended_use, r)


# --------------------------------------------------------------------------- #
# Pinning and snapshots (run in worker threads: no database access here)
# --------------------------------------------------------------------------- #
def _git(*args: str, cwd: Path | None = None, timeout: int = 600) -> str:
    env = {**os.environ, "GIT_TERMINAL_PROMPT": "0", "GIT_ASKPASS": "true", "LC_ALL": "C"}
    res = subprocess.run(["git", *args], cwd=cwd, env=env, capture_output=True, text=True, timeout=timeout)
    if res.returncode != 0:
        raise RuntimeError(f"git {args[0]} failed: {(res.stderr or res.stdout).strip()[:500]}")
    return res.stdout


def remote_head(url: str, branch: str) -> str:
    ref = "HEAD" if branch == "HEAD" else f"refs/heads/{branch}"
    out = _git("ls-remote", url, ref, timeout=120).split()
    if not out:
        raise RuntimeError(f"branch {branch} not found at {url}")
    return out[0]


def pinned_commit(lock: SourceLock, info: RepoInfo, *, update: bool) -> str:
    """Same lock entries as the module scraper: {ref, commit} under `repos`."""
    locked = lock.get("repos", info.full_name)
    if locked and locked.get("commit") and locked.get("ref") == info.default_branch and not update:
        return str(locked["commit"])
    commit = remote_head(info.url, info.default_branch)
    lock.set("repos", info.full_name, {"ref": info.default_branch, "commit": commit})
    return commit


@dataclass
class Snapshot:
    files: dict[str, bytes] = field(default_factory=dict)
    too_large: dict[str, int] = field(default_factory=dict)
    licence_text: str | None = None


def take_snapshot(url: str, commit: str, workdir: Path, cfg: ReposCfg) -> Snapshot:
    """Shallow, blobless, sparse clone of one commit; returns the selected files."""
    if workdir.exists():
        shutil.rmtree(workdir)
    workdir.mkdir(parents=True)
    t = cfg.clone_timeout_s
    try:
        _git("init", "-q", str(workdir), timeout=60)
        _git("remote", "add", "origin", url, cwd=workdir, timeout=60)
        _git("sparse-checkout", "set", "--no-cone", "--", *cfg.sparse_patterns, cwd=workdir, timeout=60)
        _git("fetch", "-q", "--depth", "1", "--filter=blob:none", "origin", commit, cwd=workdir, timeout=t)
        _git("checkout", "-q", "FETCH_HEAD", cwd=workdir, timeout=t)
        snap = Snapshot()
        excluded = [glob_to_regex(p) for p in cfg.exclude_paths]
        for p in sorted(workdir.rglob("*")):
            if not p.is_file() or ".git" in p.relative_to(workdir).parts:
                continue
            rel = p.relative_to(workdir).as_posix()
            if any(rx.match(rel) for rx in excluded):
                continue
            size = p.stat().st_size
            if "/" not in rel and LICENCE_NAMES.match(rel):
                snap.licence_text = snap.licence_text or p.read_text(encoding="utf-8", errors="replace")
                continue
            if size > cfg.max_file_bytes:
                snap.too_large[rel] = size
                continue
            snap.files[rel] = p.read_bytes()
        return snap
    finally:
        shutil.rmtree(workdir, ignore_errors=True)


def write_tarball(path: Path, snap: Snapshot) -> None:
    import io

    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.part")
    with tarfile.open(tmp, "w:gz", compresslevel=6) as tar:
        for rel, data in snap.files.items():
            ti = tarfile.TarInfo(rel)
            ti.size = len(data)
            ti.mtime = 0
            tar.addfile(ti, io.BytesIO(data))
        if snap.licence_text is not None:
            data = snap.licence_text.encode("utf-8")
            ti = tarfile.TarInfo("LICENSE")
            ti.size = len(data)
            tar.addfile(ti, io.BytesIO(data))
    tmp.replace(path)


# --------------------------------------------------------------------------- #
# File classification
# --------------------------------------------------------------------------- #
def file_kind(path: str) -> str:
    name = PurePosixPath(path).name
    if name.endswith(".bal"):
        return "bal"
    if name == "Ballerina.toml":
        return "toml"
    if name.endswith(".out"):
        return "out"
    return "md"


@dataclass(frozen=True)
class Project:
    distribution: str | None  # `distribution = "..."`, often absent in newer projects
    era: str | None           # `[package]` = Swan Lake, `[project]` = Ballerina 1.x


def project_roots(paths: list[str], texts: dict[str, str]) -> dict[str, Project]:
    """{project folder: Project} for every Ballerina.toml."""
    out: dict[str, Project] = {}
    for p in paths:
        if PurePosixPath(p).name == "Ballerina.toml":
            folder = str(PurePosixPath(p).parent)
            text = texts.get(p, "")
            m = DISTRIBUTION_RE.search(text)
            era = ("swan_lake" if re.search(r"^\s*\[package\]", text, re.M)
                   else "legacy" if re.search(r"^\s*\[project\]", text, re.M) else None)
            out["" if folder == "." else folder] = Project(m.group(1) if m else None, era)
    return out


def nearest_project(path: str, roots: dict[str, Project]) -> str | None:
    parts = PurePosixPath(path).parent.parts
    for i in range(len(parts), -1, -1):
        cand = "/".join(parts[:i])
        if cand in roots:
            return cand
    return None


def classify_syntax(code: str, project: Project | None) -> str:
    """swan_lake | legacy | unknown for one .bal file.

    Order: the project's `distribution`, 1.x-only constructs in the file, the Ballerina.toml
    layout (`[package]` vs `[project]`), then Swan Lake-only constructs in the file.
    """
    if project and project.distribution:
        d = project.distribution.lower()
        if d.startswith("2201."):
            return "swan_lake"
        if "slalpha" in d or "slbeta" in d or version_tuple(d)[:1] in ((0,), (1,)):
            return "legacy"
    if LEGACY_RE.search(code):
        return "legacy"
    if project and project.era:
        return project.era
    return "swan_lake" if SWAN_LAKE_RE.search(code) else "unknown"


def is_generated(path: str, code: str, repo: str) -> bool:
    return bool(GENERATED_RE.search(code[:1500])) or "openapi-connectors" in repo


# --------------------------------------------------------------------------- #
# Storing
# --------------------------------------------------------------------------- #
def store_files(db: Database, repo_id: int, snap: Snapshot, full_name: str, hasher: MinHasher) -> dict[str, int]:
    db.execute("DELETE FROM repo_files WHERE repo_id = ?", (repo_id,))
    texts = {p: b.decode("utf-8", errors="replace") for p, b in snap.files.items()}
    roots = project_roots(list(texts), texts)
    now = utc_now_iso()
    rows: list[tuple] = []
    counts = {"files": 0, "bal_files": 0, "legacy": 0, "generated": 0, "too_large": len(snap.too_large)}
    for path, text in texts.items():
        kind = file_kind(path)
        root = nearest_project(path, roots)
        project = roots.get(root) if root is not None else None
        dist = project.distribution if project else None
        syntax = generated = chash = sig = None
        status = "context"
        if kind == "bal":
            syntax = classify_syntax(text, project)
            generated = int(is_generated(path, text, full_name))
            chash = code_hash(text)
            sig = hasher.to_bytes(hasher.signature(text))
            status = "legacy" if syntax == "legacy" else "kept"
            counts["bal_files"] += 1
            counts["legacy"] += syntax == "legacy"
            counts["generated"] += generated
        rows.append((repo_id, path, kind, len(snap.files[path]), text, root, dist, syntax, generated or 0,
                     chash, sig, status, now, now))
        counts["files"] += 1
    for path, size in snap.too_large.items():
        rows.append((repo_id, path, file_kind(path), size, None, None, None, None, 0, None, None, "too_large",
                     now, now))
    db.conn.executemany(
        "INSERT INTO repo_files (repo_id, path, kind, bytes, text, project_root, distribution, syntax, generated, "
        "code_hash, minhash, status, created_at, updated_at) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)", rows)
    db.conn.commit()
    return counts


def upsert_repo(db: Database, info: RepoInfo, values: dict[str, Any]) -> int:
    row = db.one("SELECT id FROM repos WHERE full_name = ?", (info.full_name,))
    base = {"grp": info.group, "priority": info.priority, "url": info.url, "default_branch": info.default_branch,
            "spdx_reported": info.spdx_reported, "stars": info.meta.get("stargazers_count"),
            "size_kb": info.meta.get("size"), "pushed_at": info.meta.get("pushed_at"), **values}
    if row:
        if info.group == "manual":  # `--repo` on a repo a group already found: keep its group
            base.pop("grp")
            base.pop("priority")
        db.update("repos", row["id"], base)
        return int(row["id"])
    return db.insert("repos", {"full_name": info.full_name, **base})


def dedup(db: Database, threshold: float) -> dict[str, int]:
    """Mark exact and near-duplicate .bal files across all collected repos (earlier group wins)."""
    db.execute("UPDATE repo_files SET status = 'kept', dup_of = NULL "
               "WHERE kind = 'bal' AND status IN ('duplicate', 'near_duplicate')")
    rows = db.query(
        "SELECT f.id, f.code_hash, f.minhash FROM repo_files f JOIN repos r ON r.id = f.repo_id "
        "WHERE f.kind = 'bal' AND f.status = 'kept' AND r.status = 'collected' "
        "ORDER BY r.priority, r.id, f.path")
    hasher = MinHasher()
    lsh = LSH(threshold=threshold)
    first: dict[str, int] = {}
    exact: list[tuple[int, int]] = []
    near: list[tuple[int, int]] = []
    for r in rows:
        if r["code_hash"] in first:
            exact.append((first[r["code_hash"]], r["id"]))
            continue
        first[r["code_hash"]] = r["id"]
        if r["minhash"] is None:
            continue
        sig = hasher.from_bytes(r["minhash"])
        match = lsh.query(sig)
        if match is not None:
            near.append((match, r["id"]))
            continue
        lsh.add(r["id"], sig)
    now = utc_now_iso()
    db.conn.executemany("UPDATE repo_files SET status = 'duplicate', dup_of = ?, updated_at = ? WHERE id = ?",
                        [(a, now, b) for a, b in exact])
    db.conn.executemany("UPDATE repo_files SET status = 'near_duplicate', dup_of = ?, updated_at = ? WHERE id = ?",
                        [(a, now, b) for a, b in near])
    db.conn.commit()
    return {"bal_checked": len(rows), "duplicate": len(exact), "near_duplicate": len(near),
            "kept": len(rows) - len(exact) - len(near)}


# --------------------------------------------------------------------------- #
# The command
# --------------------------------------------------------------------------- #
def _register_fields(info: RepoInfo, spdx: str | None, verdict: str, note: str, commit: str | None = None,
                     licence_sha: str | None = None, files: int | None = None) -> dict[str, Any]:
    return {"spdx": spdx or info.spdx_reported or "", "verdict": verdict, "intended_use": info.intended_use,
            "size_kb": info.meta.get("size"), "pinned_sha": commit, "notes": note,
            "licence_file_sha256": licence_sha, "files": files}


def collect_repos(s: Settings, db: Database, run: RunTracker, api: GithubApi, lock: SourceLock, *,
                  groups: list[str] | None = None, extra: list[str] | None = None,
                  update_lock: bool = False, refresh: bool = False) -> dict[str, Any]:
    cfg = s.repos
    if groups is None and extra:
        groups = []  # `--repo` alone: just those repos
    unknown = sorted(set(groups or []) - {g.name for g in cfg.groups})
    if unknown:
        raise ConfigError(f"unknown repo group(s) {unknown}; repos.groups has {[g.name for g in cfg.groups]}")
    register = LicenceRegister(s.path(cfg.register_file))
    hasher = MinHasher()
    limit = s.limit_repos
    work_root = s.cache_dir / "repos"
    stats: dict[str, Any] = {"listed": 0, "cloned": 0, "collected": 0, "unchanged": 0, "excluded": 0,
                             "licence_check": 0, "failed": 0, "too_big": 0}
    pending: list[tuple[RepoInfo, str, int, Future[Snapshot]]] = []
    submitted = 0

    def finish(info: RepoInfo, commit: str, repo_id: int, fut: Future[Snapshot]) -> None:
        try:
            snap = fut.result()
        except Exception as exc:  # network, git or timeout: recorded, retried next run
            db.update("repos", repo_id, {"status": "failed", "error": str(exc)[:2000], "commit_sha": commit})
            stats["failed"] += 1
            run.count("repos_failed")
            log.warning("%s: %s", info.full_name, exc)
            return
        stats["cloned"] += 1
        row = register.get(info.full_name)
        detected = detect_licence(snap.licence_text)
        verdict, note, spdx = decide(info.spdx_reported, detected, row, licence_file=snap.licence_text is not None,
                                     has_licence_key=info.has_licence_key)
        lic_sha = sha256_text(snap.licence_text) if snap.licence_text else None
        n_files = len(snap.files) + len(snap.too_large)
        register.upsert(info.full_name, **_register_fields(info, spdx, verdict, note, commit, lic_sha, n_files))
        values: dict[str, Any] = {"commit_sha": commit, "spdx": spdx, "verdict": verdict, "licence_note": note,
                                  "licence_sha256": lic_sha, "error": None, "collected_at": utc_now_iso()}
        if verdict != "safe":
            db.execute("DELETE FROM repo_files WHERE repo_id = ?", (repo_id,))
            status = "excluded" if verdict == "exclude" else "licence_check"
            db.update("repos", repo_id, {**values, "status": status, "files": n_files, "bal_files": None,
                                         "snapshot": None})
            stats[status] += 1
            run.count(f"repos_{status}")
            return
        counts = store_files(db, repo_id, snap, info.full_name, hasher)
        snapshot = None
        if cfg.keep_snapshots:
            owner, name = info.full_name.split("/", 1)
            rel = f"repos/{owner}__{name}@{commit[:12]}.tar.gz"
            for old in (s.data_root / "repos").glob(f"{owner}__{name}@*.tar.gz"):
                old.unlink()
            write_tarball(s.data_root / rel, snap)
            snapshot = rel
        db.update("repos", repo_id, {**values, "status": "collected", "files": counts["files"],
                                     "bal_files": counts["bal_files"], "snapshot": snapshot,
                                     "meta": json.dumps({k: counts[k] for k in ("legacy", "generated", "too_large")})})
        stats["collected"] += 1
        run.count("repos_collected")
        log.info("%s@%s: %d files (%d .bal), %s", info.full_name, commit[:12], counts["files"], counts["bal_files"],
                 spdx)

    try:
        with ThreadPoolExecutor(max_workers=max(1, cfg.workers)) as pool:
            for info in iter_repos(api, cfg, groups, extra):
                stats["listed"] += 1
                existing = db.one("SELECT id, status, commit_sha FROM repos WHERE full_name = ?", (info.full_name,))
                row = register.get(info.full_name)
                gate = pre_gate(info.spdx_reported, row, has_licence_key=info.has_licence_key)
                if gate:
                    verdict, note = gate
                    upsert_repo(db, info, {"status": "excluded", "verdict": verdict, "licence_note": note,
                                           "spdx": info.spdx_reported})
                    # unlicensed search hits stay in the database only, so the register lists repos that
                    # were actually reviewed (or that people already track)
                    if row or info.has_licence_key:
                        register.upsert(info.full_name, **_register_fields(info, None, verdict, note))
                    stats["excluded"] += 1
                    continue
                if cfg.max_repo_kb and int(info.meta.get("size") or 0) > cfg.max_repo_kb:
                    stats["too_big"] += 1
                    continue
                locked = lock.get("repos", info.full_name)
                newly_verified = bool(existing and existing["status"] == "licence_check" and row
                                      and (row.get("notes") or "").lower().startswith("verified:"))
                if (existing and existing["status"] in ("collected", "excluded", "licence_check") and not refresh
                        and not update_lock and not newly_verified and locked
                        and existing["commit_sha"] == locked.get("commit")):
                    stats["unchanged"] += 1
                    continue
                if limit and submitted >= limit:
                    break
                try:
                    commit = pinned_commit(lock, info, update=update_lock)
                except Exception as exc:
                    upsert_repo(db, info, {"status": "failed", "error": str(exc)[:2000]})
                    stats["failed"] += 1
                    continue
                if (existing and existing["status"] == "collected" and existing["commit_sha"] == commit
                        and not refresh):
                    stats["unchanged"] += 1
                    continue
                repo_id = upsert_repo(db, info, {"status": existing["status"] if existing else "failed"})
                workdir = work_root / info.full_name.replace("/", "__")
                pending.append((info, commit, repo_id, pool.submit(take_snapshot, info.url, commit, workdir, cfg)))
                submitted += 1
                done = [p for p in pending if p[3].done()]
                for p in done:
                    pending.remove(p)
                    finish(*p)
            for p in pending:
                finish(*p)
            pending.clear()
    finally:
        lock.save()
        register.save()
    stats["dedup"] = dedup(db, cfg.near_duplicate_threshold)
    run.stats.update({k: v for k, v in stats.items() if isinstance(v, int)})
    return stats
